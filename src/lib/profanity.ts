// Numeric / symbol hate codes (whole-token only).
const HATE_CODE_RE = /(?<![\p{L}\p{N}])(?:1488|8814|14\/88|88\/14)(?![\p{L}\p{N}])/u;

// Unicode-aware "word boundary" around each Latin/Cyrillic blocked word.
const WORD_PATTERN = new RegExp(
  `(?<![\\p{L}\\p{N}])(?:${WORD_BLOCKED.map(escapeRegex).join("|")})(?![\\p{L}\\p{N}])`,
  "iu"
);

export function isProfane(text: string): boolean {
  if (!text.trim()) return false;

  const normalized = normalizeForMatch(text);

  // 1. Latin/Cyrillic word-boundary match.
  if (WORD_PATTERN.test(normalized)) return true;

  // 2. Hate-code numeric match.
  if (HATE_CODE_RE.test(normalized)) return true;

  // 3. CJK / Arabic substring match on the raw-lowercased text
  //    (leetspeak substitutions are meaningless for these scripts).
  const lower = text.toLowerCase();
  for (const token of SUBSTRING_BLOCKED) {
    if (lower.includes(token)) return true;
  }

  // 4. Multi-word phrases after punctuation/space collapse.
  const collapsed = collapseForPhrases(text);
  if (!collapsed) return false;
  for (const phrase of BLOCKED_PHRASES) {
    if (collapsed.includes(phrase)) return true;
  }

  return false;
}

/** Joins optional display name, comment body, and reply @handle for profanity scanning (all share the same filter). */
export function combinedCommentText(parts: {
  name?: string | null;
  body?: string | null;
  reply_to_name?: string | null;
}): string {
  return [parts.name, parts.body, parts.reply_to_name]
    .map((s) => (typeof s === "string" ? s : ""))
    .join(" ");
}
