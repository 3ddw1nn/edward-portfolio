function escapeRegex(s: string) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

/**
 * Lowercase alphanumerics + common leetspeak substitutions for matching.
 * Leaves diacritics/Unicode intact (Vietnamese, Cyrillic, CJK).
 */
function normalizeForMatch(s: string): string {
  return s
    .toLowerCase()
    .replace(/0/g, "o")
    .replace(/1/g, "i")
    .replace(/3/g, "e")
    .replace(/4/g, "a")
    .replace(/5/g, "s")
    .replace(/7/g, "t")
    .replace(/@/g, "a")
    .replace(/\$/g, "s");
}

/** Collapse punctuation/spaces for phrase matching (Latin-only phrases). */
function collapseForPhrases(s: string): string {
  return normalizeForMatch(s)
    .replace(/[^\p{L}\p{N}]+/gu, " ")
    .replace(/\s+/g, " ")
    .trim();
}

